// What a commit message may say, shared by the agent hook (check-commit-message.mjs, before the command runs)
// and the git hook (git/commit-msg, on every commit to the brain, scripts included).
// The owner, 2026-10-13: a commit never says an AI wrote it or helped write it. No agent line, no co-author, no
// "generated with". Only the credit is refused: a commit about the product ("use the Claude API key for the
// chat") keeps the word, because product repositories work with these models.

// Coding agents and assistants that could be named as the author. Models a product calls (Gemini, GPT) are
// left out on purpose: "slides generated with Gemini" describes the product, not the commit.
const WHO = '(?:claude(?:\\s+code)?|havok|anthropic|copilot|codex|cursor|chatgpt)';
// "built with the Claude API" names a dependency, not an author.
const NOT_A_PRODUCT = '(?!\\s+(?:api|sdk|key|keys|model|models|opus|sonnet|haiku|agent\\s+sdk|\\d))';

// Whole lines that exist only to say which tool or agent made the change. Any co-author line is refused:
// the owner is the only author.
export const CREDIT_LINE = /^\s*(co-authored-by:.*|agent:.*|.*generated (?:with|by) .*(claude|havok|anthropic|copilot|codex|chatgpt).*|claude-session:.*|.*noreply@anthropic\.com.*)$/i;

// Credit phrases inside a sentence, with the comma or bracket before them: "written by Claude",
// "made with Claude Code", "(by Havok)", and "(generated by AI)" at the end of a line.
export const CREDIT_PHRASE = new RegExp(
  '\\s*[,;(]?\\s*\\b(?:(?:written|made|generated|created|authored|co-authored|done|built|produced|drafted|coded|assisted|fixed|implemented|reviewed)\\s+(?:by|with|using|via)|by|with\\s+help\\s+from|thanks\\s+to)\\s+(?:'
  + '(?:the\\s+)?' + WHO + '\\b' + NOT_A_PRODUCT
  + '|(?:an?\\s+|the\\s+)?(?:ai|llm)(?:\\s+(?:agent|assistant|model))?(?=[\\s)."\']*$)'
  + ')\\)?', 'gim');

// The agent named as the one who did the work: "Havok fixed the search", "Claude added the tests".
export const AI_AS_AUTHOR = new RegExp('(?<![\\w./\\\\-])(' + WHO + '|the\\s+ai(?:\\s+(?:agent|assistant))?)\\s+(?:has\\s+|have\\s+)?(?:fixed|added|wrote|written|made|created|implemented|changed|updated|generated|refactored|did|built|removed|rewrote|cleaned|drafted|committed)\\b', 'i');

// The message with every credit taken out and the spacing tidied.
export function withoutCredit(text) {
  const kept = String(text).split('\n').filter((l) => !l.startsWith('#') && !CREDIT_LINE.test(l))
    .map((l) => l.replace(CREDIT_PHRASE, '').replace(/\s+$/, ''));
  return kept.join('\n').replace(/\n{3,}/g, '\n\n').replace(/\s+$/, '');
}

export function problemsIn(text) {
  const problems = [];
  const s = String(text);
  if (s.split('\n').some((l) => CREDIT_LINE.test(l)) || /\bco-authored-by:/i.test(s)) problems.push('it has a line naming a co-author, an agent or a tool as the author');
  else if (/\bagent:\s*havok/i.test(s)) problems.push('it has an agent line');
  CREDIT_PHRASE.lastIndex = 0;
  if (CREDIT_PHRASE.test(s)) problems.push('it credits an AI for the change');
  CREDIT_PHRASE.lastIndex = 0;
  if (AI_AS_AUTHOR.test(s)) problems.push('it names an AI as the one who made the change');
  return problems;
}

export const HOW_TO_WRITE = 'A commit message says what changed and why, and nothing about who or what wrote it: no '
  + '"Agent:" line, no Co-Authored-By, no "generated with", no "written by" or "fixed by" an AI, and no AI as the '
  + 'subject ("Claude fixed..."). Naming a product the change is about is fine ("use the Claude API key").';

// A command that commits with a message of its own: the agent hook checks it before it runs. A commit that reuses
// the existing message has nothing new to check.
export const COMMIT_CMD = /\bgit\b[^\n|;&]*\bcommit\b/;
export const writesMessage = (cmd) => /\s(-m|--message|-F|--file|-am|-cm)\b/.test(cmd) || /\s-[a-zA-Z]*m\b/.test(cmd);
export function commandProblems(cmd) {
  const c = String(cmd || '');
  if (!COMMIT_CMD.test(c) || !writesMessage(c)) return [];
  return problemsIn(c);
}
